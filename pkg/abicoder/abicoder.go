package abicoder

import (
	"errors"
	"fmt"
	"reflect"

	"github.com/ethereum/go-ethereum/accounts/abi"
	"github.com/flare-foundation/go-flare-common/pkg/panics"
)

type Coder[T any] struct {
	args abi.Arguments
}

// New returns a Coder for arg and T. It refuses an arg whose type [Decode]
// doesn't support, and with ErrShapeMismatch a T whose shape Decode refuses
// and one Encode can't take every tuple component from, so Encode and Decode
// check only the data.
//
// The fields of each struct in T must be in the order of the tuple's
// components and named for them, by an abi tag or as abi.ToCamelCase names
// them: Decode fills the fields by position, while Encode takes each component
// from the field named for it. Structs generated by abigen, v1 or v2, match:
// one field per component, in order, named abi.ToCamelCase of the component.
// Where two components camel-case to one name abigen suffixes the second
// field, which go-ethereum can't encode either, so New refuses it.
func New[T any](arg abi.Argument) (*Coder[T], error) {
	if err := checkArgType(arg.Type); err != nil {
		return nil, err
	}

	// before checkShape, as GetType panics on some types checkType refuses
	if err := checkType(&arg.Type); err != nil {
		return nil, err
	}

	if err := checkShape[T](arg.Type); err != nil {
		return nil, err
	}

	if err := checkNames(reflect.TypeFor[T](), &arg.Type); err != nil {
		return nil, err
	}

	return &Coder[T]{args: abi.Arguments{arg}}, nil
}

func MustNew[T any](arg abi.Argument) *Coder[T] {
	c, err := New[T](arg)
	if err != nil {
		panic(err)
	}

	return c
}

func (c *Coder[T]) Encode(data T) (encoded []byte, err error) {
	defer panics.Recover(&err)

	if err := checkRange(&c.args[0].Type, reflect.ValueOf(data)); err != nil {
		return nil, fmt.Errorf("encoding type %T: %w", data, err)
	}

	encoded, err = c.args.Pack(data)
	if err != nil {
		return nil, fmt.Errorf("encoding type %T: %w", data, err)
	}

	if err := checkData(c.args, encoded); err != nil {
		return nil, fmt.Errorf("encoding type %T: %w", data, err)
	}

	return encoded, nil
}

func (c *Coder[T]) Decode(data []byte) (t T, err error) {
	defer panics.Recover(&err)

	if err := checkData(c.args, data); err != nil {
		return t, err
	}

	values, err := c.args.Unpack(data)
	if err != nil {
		return t, err
	}

	if err := checkEncodeDecode(&c.args, data, values); err != nil {
		return t, err
	}

	x := abi.ConvertType(values[0], new(T))

	tp, ok := x.(*T)
	if !ok {
		return t, errors.New("invalid type assertion")
	}
	t = *tp

	return t, nil
}

func (c *Coder[T]) DecodeTo(data []byte, dest *T) error {
	rv := reflect.ValueOf(dest)
	if rv.Kind() != reflect.Pointer || rv.IsNil() {
		return errNonPointer
	}

	t, err := c.Decode(data)
	if err != nil {
		return err
	}

	*dest = t

	return nil
}
